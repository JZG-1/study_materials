def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def main():
    os.makedirs(DST, exist_ok=True)
    all_files = []
    for dirpath, dirnames, filenames in os.walk(ROOT):
        if os.path.abspath(dirpath).startswith(os.path.abspath(DST)):
            continue
        for fn in filenames:
            all_files.append(os.path.relpath(os.path.join(dirpath, fn), ROOT))

    drop_set = set(DROP)
    moved, dropped, skipped = [], [], []

    for rel in sorted(all_files):
        src = os.path.join(ROOT, rel)
        if rel in drop_set:
            os.remove(src)
            dropped.append(rel)
            continue
        if rel not in MAP:
            skipped.append(rel)
            continue
        dst = os.path.join(DST, MAP[rel].replace("\\", os.sep))
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.move(src, dst)
        moved.append((rel, MAP[rel]))

    # 清理空目录
    for dirpath, dirnames, filenames in os.walk(ROOT, topdown=False):
        if os.path.abspath(dirpath).startswith(os.path.abspath(DST)):
            continue
        if dirpath == ROOT:
            continue
        if not os.listdir(dirpath):
            os.rmdir(dirpath)

    print("移动:", len(moved), " 删除:", len(dropped), " 未分类:", len(skipped))
    for s in skipped:
        print("  未分类:", s)


if __name__ == "__main__":
    main()
